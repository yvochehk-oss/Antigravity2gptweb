#!/bin/bash
# ==============================================================================
# 成都建工·天府掌舵 —— 启动移动端 Web 预览服务 (可在手机浏览器直接测试)
# ==============================================================================

cd "$(dirname "$0")"
GREEN='\033[0;32m'
GOLD='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

LOCAL_IP=$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo "127.0.0.1")

echo -e "${GOLD}==============================================================================${NC}"
echo -e "${GOLD}  📱 成都建工·天府掌舵 (老板端移动驾驶舱)${NC}"
echo -e "${GOLD}==============================================================================${NC}"
echo -e "${GREEN}  🏢 本机浏览器预览: http://127.0.0.1:5173${NC}"
echo -e "${CYAN}  📲 同局域网手机扫码/浏览器打开: http://${LOCAL_IP}:5173${NC}"
echo -e "${GOLD}==============================================================================${NC}"
echo ""

npm run dev
